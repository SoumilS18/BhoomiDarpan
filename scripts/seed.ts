async function seedProjectsAndCases(
  rfctlarrId: string,
  chains: GeoChain[]
): Promise<void> {
  const { data: existingProjects } = await supabase.from('projects').select('id, code');

  // Project definitions carry NO geography: each one is bound to a chain that
  // was resolved from the database a moment ago.
  const projectDefs = [
    {
      code: 'DEMO-PRJ-01',
      name: `${DEMO_LABEL} — Industrial Corridor Logistics Node`,
      description: `${DEMO_NOTE} Multi-modal logistics hub and industrial corridor package.`,
      project_type: 'industrial',
      sponsoring_agency: 'Demonstration sponsoring agency (sample data)',
      estimated_budget: 850000000,
      target_completion_date: '2027-12-31',
      status: 'in_progress',
    },
    {
      code: 'DEMO-PRJ-02',
      name: `${DEMO_LABEL} — Dedicated Freight Corridor Package`,
      description: `${DEMO_NOTE} Electrified double-track freight railway corridor alignment.`,
      project_type: 'railway',
      sponsoring_agency: 'Demonstration sponsoring agency (sample data)',
      estimated_budget: 1200000000,
      target_completion_date: '2028-06-30',
      status: 'in_progress',
    },
    {
      code: 'DEMO-PRJ-03',
      name: `${DEMO_LABEL} — Highway Bypass Widening`,
      description: `${DEMO_NOTE} Bypass expansion to alleviate arterial traffic congestion.`,
      project_type: 'highway',
      sponsoring_agency: 'Demonstration sponsoring agency (sample data)',
      estimated_budget: 450000000,
      target_completion_date: '2026-11-30',
      status: 'in_progress',
    },
  ];

  const projectIds: string[] = [];
  for (const p of projectDefs) {
    const found = existingProjects?.find((ep) => ep.code === p.code);
    if (found) {
      projectIds.push(found.id);
      continue;
    }
    const { data, error } = await supabase.from('projects').insert(p).select('*').single();
    if (error) throw error;
    projectIds.push(data.id);
  }

  const { data: existingCases } = await supabase
    .from('acquisition_cases')
    .select('id, case_number');

  for (let idx = 0; idx < chains.length && idx < 3; idx++) {
    const chain = chains[idx];
    const projectId = projectIds[idx % projectIds.length];

    const caseNumber = `DEMO-${chain.state.code}-${chain.district.code}-2026-${100 + idx}`;

    if (existingCases?.some((ec) => ec.case_number === caseNumber)) continue;

    const { data: newCase, error: caseErr } = await supabase
      .from('acquisition_cases')
      .insert({
        case_number: caseNumber,
        project_id: projectId,
        workflow_id: rfctlarrId,
        title: `${DEMO_LABEL} — acquisition case ${caseNumber}`,
        description: `${DEMO_NOTE} Located in ${chain.village.name}, ${chain.subDistrict.name} sub-district, ${chain.district.name} district, ${chain.state.name}.`,
        state: chain.state.name,
        district: chain.district.name,
        tehsil: chain.subDistrict.name,
        village: chain.village.name,
        state_lgd_code: chain.state.code,
        district_lgd_code: chain.district.code,
        subdistrict_lgd_code: chain.subDistrict.code,
        village_lgd_code: chain.village.code,
        total_area_hectares: 34.5,
        estimated_compensation: 145000000,
        status: idx === 0 ? 'delayed' : 'active',
        priority: idx === 0 ? 'high' : 'medium',
        start_date: '2026-03-01',
        expected_completion_date: '2026-12-15',
      })
      .select('*')
      .single();
    if (caseErr) throw caseErr;

    // Deterministic parcel identifiers — no Math.random(), so a re-run and a
    // fresh database always produce the same rows.
    const parcelSeed = 101 + idx * 10;
    const { error: parcelErr } = await supabase.from('parcels').insert([
      {
        case_id: newCase.id,
        survey_number: `SY-${parcelSeed}/1`,
        khata_number: `KH-${20 + idx}`,
        landowner_names: [`Demonstration landowner ${parcelSeed}A (sample record)`],
        land_type: 'Agricultural Irrigated',
        area_acres: 4.25,
        compensation_amount: 18500000,
        acquisition_status: 'notified',
      },
      {
        case_id: newCase.id,
        survey_number: `SY-${parcelSeed}/2`,
        khata_number: `KH-${21 + idx}`,
        landowner_names: [`Demonstration landowner ${parcelSeed}B (sample record)`],
        land_type: 'Agricultural Fallow',
        area_acres: 6.8,
        compensation_amount: 24000000,
        acquisition_status: 'identified',
      },
    ]);
    if (parcelErr) throw parcelErr;

    const { stageInstances, expectedCompletionDate } = await initializeCaseWorkflow(
      newCase.id,
      rfctlarrId,
      newCase.start_date
    );

    await supabase
      .from('acquisition_cases')
      .update({ expected_completion_date: expectedCompletionDate })
      .eq('id', newCase.id);

    // Demonstrate real stage progression through the real engine.
    if (idx === 0 && stageInstances.length >= 4) {
      await advanceStageInstance({
        caseId: newCase.id,
        stageInstanceId: stageInstances[0].id,
        targetStatus: 'completed',
        actualDate: '2026-03-25',
        notes: `${DEMO_LABEL}: preliminary notification gazetted (sample record).`,
        actorName: DEMO_ACTOR,
      });
      await advanceStageInstance({
        caseId: newCase.id,
        stageInstanceId: stageInstances[1].id,
        targetStatus: 'completed',
        actualDate: '2026-05-20',
        notes: `${DEMO_LABEL}: objection hearing completed (sample record).`,
        actorName: DEMO_ACTOR,
      });
      await advanceStageInstance({
        caseId: newCase.id,
        stageInstanceId: stageInstances[2].id,
        targetStatus: 'completed',
        actualDate: '2026-06-18',
        notes: `${DEMO_LABEL}: declaration approved and published (sample record).`,
        actorName: DEMO_ACTOR,
      });
    }

    await supabase.from('case_events').insert({
      case_id: newCase.id,
      event_type: 'CASE_CREATED',
      title: `Demonstration case ${caseNumber} registered`,
      description: `${DEMO_NOTE} Registered with ${newCase.total_area_hectares} hectares under ${chain.state.name} administration.`,
      actor_name: DEMO_ACTOR,
      metadata: {
        record_kind: 'demonstration',
        sample: true,
        seeded_by: 'scripts/seed.ts',
        geography_source: 'administrative_units',
        lgd_codes: {
          state: chain.state.code,
          district: chain.district.code,
          subdistrict: chain.subDistrict.code,
          village: chain.village.code,
        },
      },
    });

    console.log(
      `   seeded ${caseNumber} in ${chain.village.name} (${chain.district.name}, ${chain.state.name}) ` +
        `LGD ${chain.state.code}/${chain.district.code}/${chain.subDistrict.code}/${chain.village.code}`
    );
  }
}

async function seed() {
  console.log('BhoomiSetu demonstration seed');

  const { rfctlarrId } = await seedWorkflows();
  await seedStages(rfctlarrId);

  console.log('3. Resolving administrative geography from the database...');
  const provenance = await getGeographyProvenance();
  console.log(`   source status: ${provenance.status} | units in database: ${provenance.units_in_database}`);

  const chains = await resolveGeoChains(3);

  if (chains.length === 0) {
    console.log('\nSKIPPED: no demonstration projects or cases were created.');
    console.log(
      '  acquisition_cases.state / district / village are NOT NULL, and this script will not\n' +
        '  invent geography to satisfy them. The administrative hierarchy has not been ingested\n' +
        `  (${provenance.status}; ${provenance.units_in_database} units in the database).`
    );
    if (provenance.requires) console.log(`  Required: ${provenance.requires}`);
    console.log(
      '  Workflow definitions and stage dependencies were created above and are reusable.\n' +
        '  Re-run this script after the administrative geography hierarchy is ingested.\n'
    );
    return;
  }

  console.log(`   resolved ${chains.length} state -> district -> sub-district -> village chain(s)`);

  console.log('4. Seeding labelled demonstration projects and cases...');
  await seedProjectsAndCases(rfctlarrId, chains);

  console.log('\nSeed completed.');
  console.log(
    'All projects, cases, parcels, stage instances and audit events above are labelled\n' +
      'demonstration records stored in the database and produced by the real workflow engine.'
  );
}

seed().catch((err) => {
  console.error('Seed failed:', err);
  process.exit(1);
});
