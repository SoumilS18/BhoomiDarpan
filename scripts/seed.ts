/**
 * Seeds clearly-labelled DEMONSTRATION records into the live database.
 *
 * Design rules (these are the reason this file was rewritten):
 *
 *  1. NO geography is written by this script. State / district / tehsil /
 *     village values and their LGD codes are resolved at run time through
 *     `administrativeGeographyService` — the same service the API and the UI
 *     use. A hardcoded "Maharashtra / Pune / Maval" string here would be
 *     fabricated geography, and it would silently disagree with whatever the
 *     authoritative source actually contains.
 *
 *  2. If no hierarchy has been ingested, `acquisition_cases.state/district/
 *     village` are NOT NULL columns, so this script refuses to create cases
 *     and says so. It never invents values to satisfy the schema.
 *
 *  3. Everything it does create is explicitly labelled as demonstration data
 *     in the record itself (title, description, actor names and event
 *     metadata), and it flows through the ordinary workflow engine, audit
 *     log, notifications and analytics paths — no frontend-only fake arrays.
 *
 *  4. It is idempotent and deterministic: re-running it changes nothing, and
 *     no identifiers are randomised.
 *
 * Run: bun run scripts/seed.ts
 */
import dotenv from 'dotenv';
import path from 'path';
import { createClient } from '@supabase/supabase-js';
import { initializeCaseWorkflow, advanceStageInstance } from '../server/services/workflowEngine';
import {
  getGeographyProvenance,
  getStates,
  getDistricts,
  getSubDistricts,
  getVillages,
} from '../server/services/administrativeGeographyService';
import type { AdministrativeUnit } from '../shared/types';

dotenv.config({ path: path.resolve(process.cwd(), '.env') });

const supabaseUrl = process.env.SUPABASE_URL || process.env.VITE_SUPABASE_URL;
const supabaseKey =
  process.env.SUPABASE_SERVICE_ROLE_KEY ||
  process.env.SUPABASE_ANON_KEY ||
  process.env.VITE_SUPABASE_ANON_KEY;

if (!supabaseUrl || !supabaseKey || supabaseUrl.includes('your-supabase-project')) {
  console.error('\nERROR: Supabase credentials not found in .env!');
  console.error(
    'Set SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY in .env before running the seed.\n'
  );
  process.exit(1);
}

const supabase = createClient(supabaseUrl, supabaseKey);

const DEMO_LABEL = 'Demonstration';
const DEMO_ACTOR = 'Demonstration seed (sample data)';
const DEMO_NOTE =
  '[DEMONSTRATION RECORD — sample data generated by scripts/seed.ts to exercise the real workflow, ' +
  'audit, notification and analytics paths. This is not a real land acquisition.]';

const byCode = (a: AdministrativeUnit, b: AdministrativeUnit) =>
  a.code.localeCompare(b.code, 'en', { numeric: true });

/** A fully resolved state -> district -> sub-district -> village chain. */
interface GeoChain {
  state: AdministrativeUnit;
  district: AdministrativeUnit;
  subDistrict: AdministrativeUnit;
  village: AdministrativeUnit;
}

/**
 * Walks the ingested hierarchy deterministically (ascending LGD code order)
 * and returns up to `wanted` chains, each from a different state where the
 * data allows. Probe counts are bounded so a large hierarchy cannot turn this
 * into an unbounded number of requests.
 */
async function resolveGeoChains(wanted: number, maxProbes = 400): Promise<GeoChain[]> {
  const states = [...(await getStates())].sort(byCode);
  const chains: GeoChain[] = [];
  const usedStates = new Set<string>();
  let probes = 0;

  for (const state of states) {
    if (chains.length >= wanted) break;

    // Prefer an unused state, but allow reuse once every state is exhausted.
    if (usedStates.has(state.code) && chains.length > 0) continue;

    const districts = [...(await getDistricts(state.code))].sort(byCode);
    for (const district of districts) {
      if (chains.length >= wanted || probes >= maxProbes) break;
      if (usedStates.has(state.code) && chains.length > 0) break;

      const subDistricts = [...(await getSubDistricts(district.code))].sort(byCode);
      for (const subDistrict of subDistricts) {
        if (chains.length >= wanted || probes >= maxProbes) break;
        probes++;

        const { villages } = await getVillages(subDistrict.code, { page: 1, limit: 5 });
        const village = [...villages].sort(byCode)[0];
        if (!village) continue;

        chains.push({ state, district, subDistrict, village });
        usedStates.add(state.code);
        break;
      }
    }
  }
  return chains;
}

async function seedWorkflows(): Promise<{ rfctlarrId: string }> {
  console.log('1. Seeding workflows...');
  const { data: existingWf } = await supabase.from('workflows').select('id, code');

  const defs = [
    {
      code: 'RFCTLARR_2013',
      name: 'RFCTLARR Act 2013 Standard Acquisition',
      description:
        'Statutory land acquisition under the Right to Fair Compensation and Transparency in Land Acquisition, Rehabilitation and Resettlement Act, 2013.',
      legal_framework: 'RFCTLARR Act 2013',
      version: '1.0',
    },
    {
      code: 'DIRECT_PURCHASE',
      name: 'Direct Land Purchase & Consent Model',
      description:
        'Expedited acquisition via mutual agreement with landowners with direct compensation settlement.',
      legal_framework: 'State Direct Purchase Policy',
      version: '1.0',
    },
  ];

  let rfctlarrId = '';
  for (const d of defs) {
    const found = existingWf?.find((w) => w.code === d.code);
    if (found) {
      if (d.code === 'RFCTLARR_2013') rfctlarrId = found.id;
      continue;
    }
    const { data, error } = await supabase.from('workflows').insert(d).select('*').single();
    if (error) throw error;
    if (d.code === 'RFCTLARR_2013') rfctlarrId = data.id;
  }
  return { rfctlarrId };
}

