/**
 * Data-Driven Layer Resolver
 * Resolves verified Bhuvan WMS layers for given state codes, names, or bounding box.
 * Strictly ZERO hardcoding: matching is purely relational based on catalog attributes.
 */
export function resolveBhuvanLayers(context: BhuvanLayerContext = {}): BhuvanResolutionResult {
  const targetStateCodes = new Set<string>();

  // 1. Gather state codes from explicit codes
  if (context.state_codes && Array.isArray(context.state_codes)) {
    for (const code of context.state_codes) {
      const normalized = normalizeJurisdictionToStateCode(code);
      if (normalized) targetStateCodes.add(normalized);
    }
  }

  // 2. Gather state codes from state names
  if (context.state_names && Array.isArray(context.state_names)) {
    for (const name of context.state_names) {
      const normalized = normalizeJurisdictionToStateCode(name);
      if (normalized) targetStateCodes.add(normalized);
    }
  }

  const resolvedLayers: BhuvanResolvedLayer[] = [];
  const unsupportedJurisdictions: string[] = [];

  // Filter catalogue strictly by enabled and verified entries
  const activeCatalogue = BHUVAN_LAYER_CATALOGUE.filter(
    l => l.enabled && l.verification_status === 'verified'
  );

  // If workspace filter is provided
  const scopedCatalogue = context.workspace
    ? activeCatalogue.filter(l => l.workspace === context.workspace)
    : activeCatalogue;

  // Case A: Jurisdictions specified (single or multi-state corridor)
  if (targetStateCodes.size > 0) {
    for (const stateCode of targetStateCodes) {
      const stateLayers = scopedCatalogue.filter(l => l.state_code === stateCode);

      if (stateLayers.length === 0) {
        // Record honest missing coverage
        const stateRef = INDIAN_STATES_REFERENCE.find(s => s.code === stateCode);
        const displayName = stateRef ? stateRef.name : stateCode;
        unsupportedJurisdictions.push(displayName);
      } else {
        for (const layer of stateLayers) {
          resolvedLayers.push({
            layer,
            wms_url: BHUVAN_WMS_ROOT,
            applicable_jurisdiction: layer.state_name || stateCode,
            status: 'available',
          });
        }
      }
    }

    // Always include verified national layers matching workspace
    const nationalLayers = scopedCatalogue.filter(
      l => l.coverage === 'national'
    );
    for (const layer of nationalLayers) {
      resolvedLayers.push({
        layer,
        wms_url: BHUVAN_WMS_ROOT,
        applicable_jurisdiction: 'National',
        status: 'available',
      });
    }
  } else {
    // Case B: No jurisdiction filter passed (e.g. general layer discovery or national view)
    // Return all national layers plus state-scoped representative layers
    for (const layer of scopedCatalogue) {
      resolvedLayers.push({
        layer,
        wms_url: BHUVAN_WMS_ROOT,
        applicable_jurisdiction: layer.state_name || 'National',
        status: 'available',
      });
    }
  }

  return {
    resolved_layers: resolvedLayers,
    unsupported_jurisdictions: Array.from(new Set(unsupportedJurisdictions)),
    total_resolved: resolvedLayers.length,
    timestamp: new Date().toISOString(),
  };
}
