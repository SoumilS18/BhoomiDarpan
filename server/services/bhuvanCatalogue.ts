/**
 * Normalizes any freeform state name, alias, or code to official 2-letter code.
 */
export function normalizeJurisdictionToStateCode(input?: string | null): string | null {
  if (!input || typeof input !== 'string') return null;
  const clean = input.trim().toLowerCase();
  if (clean.length === 0) return null;

  // Direct code match
  const directMatch = INDIAN_STATES_REFERENCE.find(s => s.code.toLowerCase() === clean);
  if (directMatch) return directMatch.code;

  // Name or alias match
  const aliasMatch = INDIAN_STATES_REFERENCE.find(s => 
    s.name.toLowerCase() === clean || s.aliases.some(a => a.toLowerCase() === clean)
  );
  if (aliasMatch) return aliasMatch.code;

  return null;
}

