export type BhuvanWorkspace = 'lulc' | 'disaster' | 'admin' | 'vector' | 'moef' | 'pmgsy';

export interface BhuvanLayerEntry {
  layer_id: string;
  provider: 'bhuvan';
  workspace: BhuvanWorkspace;
  layer_name: string; // OGC layer parameter e.g. "lulc:MH_LULC50K_1516"
  title: string;
  layer_type: 'wms_raster';
  coverage: 'national' | 'state' | 'regional';
  state_code?: string; // 2-letter ISO 3166-2:IN subcode
  state_name?: string; // Canonical state name
  lgd_state_code?: number; // Ministry of Panchayati Raj LGD state code
  temporal_reference: string; // e.g. "2015–16", "2011–12", "2023"
  freshness_class: 'reference' | 'historical' | 'static';
  purpose: string;
  supported_crs: string[];
  enabled: boolean;
  verification_status: 'verified' | 'unverified' | 'unavailable';
  capabilities_verified: boolean;
  getmap_verified: boolean;
  last_verified_at: string;
  attribution: string;
  usage_notes: string;
  analytical_classification: 'supporting_spatial_context' | 'visualization';
  default_opacity: number;
}

export interface BhuvanLayerContext {
  state_codes?: string[];
  state_names?: string[];
  bbox?: [number, number, number, number];
  workspace?: BhuvanWorkspace;
}

export interface BhuvanResolvedLayer {
  layer: BhuvanLayerEntry;
  wms_url: string;
  applicable_jurisdiction?: string;
  status: 'available' | 'unavailable' | 'not_available_for_jurisdiction';
  reason?: string;
}

export interface BhuvanResolutionResult {
  resolved_layers: BhuvanResolvedLayer[];
  unsupported_jurisdictions: string[];
  total_resolved: number;
  timestamp: string;
}

